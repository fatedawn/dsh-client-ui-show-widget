/**
 * Merge the vendored UMD bundles into the client entry.
 *
 * Two constraints force this shape:
 *   - the browser half cannot read from disk, and
 *   - the host serves only `client.<name>.js` chunks, so a sibling file would
 *     not be routable.
 *
 * So the library text is emitted ahead of the plugin factory in the same file,
 * registering `__DSH_SHOW_WIDGET_VENDOR__` before `factory` runs. The source of
 * truth stays `lib/client.src.js`; `lib/client.js` is generated from it.
 *
 * Run after replacing anything under vendor/ or editing client.src.js.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const ROOT = new URL('../', import.meta.url)
const VENDOR_DIR = new URL('vendor/', ROOT)
const SRC = new URL('lib/client.src.js', ROOT)
const OUT = new URL('lib/client.js', ROOT)

const read = (path, label) => {
  if (!existsSync(path)) throw new Error(`missing ${label}: ${path.pathname}`)
  return readFileSync(path, 'utf8')
}

const mermaid = read(new URL('mermaid.min.js', VENDOR_DIR), 'mermaid')
const katexJs = read(new URL('katex.min.js', VENDOR_DIR), 'katex js')
const katexCss = read(new URL('katex.min.css', VENDOR_DIR), 'katex css')
const source = read(SRC, 'client source')

/** Embed as a JSON string so quotes, newlines and `</script>` stay inert. */
const literal = (text) => JSON.stringify(text).replace(/<\//g, '<\\/')

/**
 * Runs inside the framed document. Kept for the case where a library must be
 * booted from text rather than a parent-provided blob URL.
 */
const header = [
  '/* GENERATED by scripts/bundle-vendor.mjs from lib/client.src.js + vendor/. */',
  '/* Edit the source, not this file. */',
  '(function () {',
  `  window.__DSH_VENDOR_KATEX__ = ${literal(katexJs)};`,
  `  window.__DSH_VENDOR_MERMAID__ = ${literal(mermaid)};`,
  '  window.__DSH_SHOW_WIDGET_VENDOR__ = {',
  `    katexJs: ${literal(katexJs)},`,
  `    mermaid: ${literal(mermaid)},`,
  `    katexCss: ${literal(katexCss)}`,
  '  };',
  '})();',
  '',
  '',
].join('\n')

writeFileSync(OUT, header + source)

const kb = (text) => (Buffer.byteLength(text) / 1024).toFixed(0)
console.log('lib/client.js written')
console.log(`  mermaid      : ${kb(mermaid)}K`)
console.log(`  katex        : ${kb(katexJs)}K js + ${kb(katexCss)}K css`)
console.log(`  plugin source: ${kb(source)}K`)
console.log(`  total        : ${kb(header + source)}K`)
